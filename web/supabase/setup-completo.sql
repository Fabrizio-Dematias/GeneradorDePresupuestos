-- Edita un remito: repone el stock de los items originales, reemplaza los
-- items y datos (el número no cambia) y descuenta el stock nuevo.
-- El total nuevo es el total guardado + lo que suman los ítems nuevos − lo que
-- sumaban los anteriores: si los ítems no cambian, el total queda idéntico
-- (también en los remitos viejos cuyo total no coincide con la suma de sus
-- ítems), y si cambian, se mueve exactamente por la diferencia.
create or replace function actualizar_remito(p_remito_id bigint, p_remito jsonb, p_items jsonb)
returns jsonb
language plpgsql
as $$
declare
    v_numero text;
    v_estado text;
    v_total_anterior numeric;
    v_suma_anterior numeric;
    v_validado jsonb;
    v_items jsonb;
    v_total numeric;
    it record;
    i jsonb;
    v_cant integer;
    v_prod_id bigint;
    v_codigo text;
    v_desc text;
    v_anterior integer;
    v_nuevo integer;
begin
    select numero, coalesce(estado, 'Completado'), total
    into v_numero, v_estado, v_total_anterior
    from remitos where id = p_remito_id for update;
    if not found then
        raise exception 'Remito % no encontrado', p_remito_id;
    end if;
    if v_estado = 'Anulado' then
        raise exception 'El remito % está anulado y no se puede editar', v_numero;
    end if;

    -- Misma validación que en crear_remito, antes de tocar nada. Los ítems
    -- que no cambiaron conservan su subtotal original.
    v_validado := validar_remito(p_remito, p_items, p_remito_id);
    v_items := v_validado->'items';
    select coalesce(sum(subtotal), 0) into v_suma_anterior
    from remito_items where remito_id = p_remito_id;
    v_total := v_total_anterior + (v_validado->>'suma')::numeric - v_suma_anterior;
    if v_total < 0 then
        raise exception 'El total del remito % quedaría negativo (%). Revisá los ítems.', v_numero, v_total;
    end if;

    for it in
        select codigo, sum(cantidad) as cantidad
        from remito_items
        where remito_id = p_remito_id and coalesce(codigo, '') <> '' and cantidad > 0
        group by codigo
    loop
        update productos
        set stock = stock + it.cantidad
        where codigo = it.codigo
        returning id, codigo, descripcion, stock - it.cantidad, stock
        into v_prod_id, v_codigo, v_desc, v_anterior, v_nuevo;
        if found then
            insert into movimientos_stock (producto_id, producto_codigo, producto_descripcion,
                                           tipo, cantidad, stock_anterior, stock_nuevo, motivo, remito_id)
            values (v_prod_id, v_codigo, v_desc,
                    'ingreso', it.cantidad, v_anterior, v_nuevo,
                    'Edición · remito ' || v_numero || ' (reversión)', p_remito_id);
        end if;
    end loop;

    delete from remito_items where remito_id = p_remito_id;

    update remitos
    set fecha             = (p_remito->>'fecha')::date,
        cliente_id        = nullif(p_remito->>'cliente_id', '')::bigint,
        cliente_nombre    = p_remito->>'cliente_nombre',
        cliente_domicilio = p_remito->>'cliente_domicilio',
        cliente_cuit      = p_remito->>'cliente_cuit',
        condicion_iva     = coalesce(p_remito->>'condicion_iva', 'Consumidor Final'),
        condicion_venta   = coalesce(p_remito->>'condicion_venta', 'Contado'),
        total             = v_total,
        ruta_pdf          = 'remito_' || regexp_replace(coalesce(p_remito->>'cliente_nombre', ''), '[^a-zA-Z0-9]', '_', 'g')
                                || '_' || v_numero || '.pdf'
    where id = p_remito_id;

    insert into remito_items (remito_id, codigo, cantidad, descripcion, precio_unitario, bonificacion, subtotal)
    select
        p_remito_id,
        elem->>'codigo',
        (elem->>'cantidad')::integer,
        elem->>'descripcion',
        (elem->>'precio_unitario')::numeric,
        (elem->>'bonificacion')::numeric,
        (elem->>'subtotal')::numeric
    from jsonb_array_elements(v_items) as elem;

    for i in select * from jsonb_array_elements(v_items)
    loop
        v_cant := coalesce((i->>'cantidad')::integer, 0);
        if v_cant > 0 and coalesce(i->>'codigo', '') <> '' then
            update productos
            set stock = stock - v_cant
            where codigo = (i->>'codigo')
            returning id, codigo, descripcion, stock + v_cant, stock
            into v_prod_id, v_codigo, v_desc, v_anterior, v_nuevo;
            if found then
                insert into movimientos_stock (producto_id, producto_codigo, producto_descripcion,
                                               tipo, cantidad, stock_anterior, stock_nuevo, motivo, remito_id)
                values (v_prod_id, v_codigo, v_desc,
                        'egreso', v_cant, v_anterior, v_nuevo,
                        'Venta · remito ' || v_numero || ' (editado)', p_remito_id);
            end if;
        end if;
    end loop;

    return jsonb_build_object('id', p_remito_id, 'numero', v_numero, 'total', v_total, 'items', v_items);
end;
$$;

-- Registra un movimiento de stock manual (ingreso/egreso/ajuste),
-- actualizando el producto y dejando el registro de auditoría.
create or replace function registrar_movimiento_stock(
    p_producto_id bigint,
    p_tipo text,
    p_cantidad integer,
    p_motivo text
)
returns integer
language plpgsql
as $$
declare
    v_codigo text;
    v_desc text;
    v_anterior integer;
    v_nuevo integer;
    v_magnitud integer;
begin
    if p_tipo in ('ingreso', 'egreso') and p_cantidad < 0 then
        raise exception 'La cantidad no puede ser negativa';
    end if;

    if p_tipo = 'ingreso' then
        -- UPDATE relativo y atómico: evita "lost update" entre movimientos concurrentes
        v_magnitud := abs(p_cantidad);
        update productos set stock = stock + v_magnitud, fecha_actualizacion = now()
        where id = p_producto_id
        returning codigo, descripcion, stock - v_magnitud, stock
        into v_codigo, v_desc, v_anterior, v_nuevo;
    elsif p_tipo = 'egreso' then
        v_magnitud := abs(p_cantidad);
        update productos set stock = stock - v_magnitud, fecha_actualizacion = now()
        where id = p_producto_id
        returning codigo, descripcion, stock + v_magnitud, stock
        into v_codigo, v_desc, v_anterior, v_nuevo;
    elsif p_tipo = 'ajuste' then
        -- Ajuste fija un valor absoluto: se toma lock de la fila (for update)
        -- para leer el stock previo de forma consistente antes de sobreescribir.
        select stock, codigo, descripcion into v_anterior, v_codigo, v_desc
        from productos where id = p_producto_id for update;
        if not found then
            raise exception 'Producto % no encontrado', p_producto_id;
        end if;
        v_nuevo := p_cantidad;
        v_magnitud := abs(p_cantidad - coalesce(v_anterior, 0));
        update productos set stock = v_nuevo, fecha_actualizacion = now()
        where id = p_producto_id;
    else
        raise exception 'Tipo de movimiento inválido: %', p_tipo;
    end if;

    if not found then
        raise exception 'Producto % no encontrado', p_producto_id;
    end if;

    insert into movimientos_stock (producto_id, producto_codigo, producto_descripcion,
                                   tipo, cantidad, stock_anterior, stock_nuevo, motivo)
    values (p_producto_id, v_codigo, v_desc,
            p_tipo, v_magnitud, coalesce(v_anterior, 0), v_nuevo, coalesce(p_motivo, ''));

    return v_nuevo;
end;
$$;

-- Aplica un aumento (o baja, con porcentaje negativo) a una categoría
-- o a todos los productos, registrando cada cambio en historial_precios.
create or replace function aplicar_aumento_precios(p_categoria text, p_porcentaje double precision)
returns integer
language plpgsql
as $$
declare
    v_count integer;
begin
    insert into historial_precios (producto_codigo, producto_descripcion, precio_anterior,
                                   precio_nuevo, porcentaje_cambio, categoria)
    select codigo, descripcion, precio_unitario,
           precio_unitario * (1 + p_porcentaje / 100.0), p_porcentaje, categoria
    from productos
    where p_categoria is null or p_categoria in ('TODAS', 'TODOS') or categoria = p_categoria;

    update productos
    set precio_unitario = precio_unitario * (1 + p_porcentaje / 100.0),
        fecha_actualizacion = now()
    where p_categoria is null or p_categoria in ('TODAS', 'TODOS') or categoria = p_categoria;

    get diagnostics v_count = row_count;
    return v_count;
end;
$$;

-- ---------- Agregaciones en el servidor ----------
-- Usadas por Dashboard, Facturación mensual y Más vendidos.
-- Todas excluyen los remitos anulados.

create or replace function facturacion_mensual()
returns table (anio integer, mes integer, cantidad bigint, total numeric)
language sql
stable
as $$
    select extract(year from fecha)::integer,
           extract(month from fecha)::integer,
           count(*),
           coalesce(sum(total), 0)
    from remitos
    where coalesce(estado, '') <> 'Anulado'
    group by 1, 2
    order by 1, 2;
$$;

create or replace function ranking_productos(p_desde date, p_limite integer, p_orden text default 'cantidad')
returns table (codigo text, descripcion text, categoria text, cantidad bigint, facturado numeric)
language sql
stable
as $$
    select coalesce(ri.codigo, '—'),
           ri.descripcion,
           coalesce(p.categoria, 'SIN CATEGORÍA'),
           sum(ri.cantidad)::bigint,
           coalesce(sum(ri.subtotal), 0)
    from remito_items ri
    join remitos r on r.id = ri.remito_id
    left join productos p on p.codigo = ri.codigo
    where coalesce(r.estado, '') <> 'Anulado'
      and (p_desde is null or r.fecha >= p_desde)
    group by 1, 2, 3
    order by case when p_orden = 'facturado' then coalesce(sum(ri.subtotal), 0)
                  else sum(ri.cantidad)::numeric end desc
    limit p_limite;
$$;

create or replace function resumen_ventas(p_desde date)
returns table (unidades bigint, productos_distintos bigint, facturado numeric)
language sql
stable
as $$
    select coalesce(sum(ri.cantidad), 0)::bigint,
           count(distinct coalesce(ri.codigo, '') || '|' || ri.descripcion),
           coalesce(sum(ri.subtotal), 0)
    from remito_items ri
    join remitos r on r.id = ri.remito_id
    where coalesce(r.estado, '') <> 'Anulado'
      and (p_desde is null or r.fecha >= p_desde);
$$;

create or replace function productos_reposicion()
returns table (codigo text, descripcion text, stock integer, stock_minimo integer)
language sql
stable
as $$
    select codigo, descripcion, stock, stock_minimo
    from productos
    where stock <= 0 or (stock_minimo > 0 and stock <= stock_minimo)
    order by stock;
$$;


-- ---------- Login por nombre de usuario ----------
-- La tabla user_profiles NO es legible con la anon key: el lookup del login
-- pasa por esta función security definer, que verifica la contraseña antes
-- de devolver el email (si no, revelaría el email de cualquier usuario).
-- Con 5 intentos fallidos en 15 minutos el usuario queda bloqueado ese rato.
create extension if not exists pgcrypto with schema extensions;
drop function if exists login_email(text);

create or replace function login_email(p_username text, p_password text)
returns text language plpgsql security definer set search_path = '' as $$
declare
    v_username text := lower(trim(coalesce(p_username, '')));
    v_email text; v_hash text;
begin
    if v_username = '' or length(v_username) > 100
       or coalesce(p_password, '') = '' or length(p_password) > 200 then
        return null;
    end if;
    delete from public.login_intentos where fecha < now() - interval '1 day';
    if (select count(*) from public.login_intentos
        where username = v_username and fecha > now() - interval '15 minutes') >= 5 then
        raise exception 'Demasiados intentos fallidos. Esperá 15 minutos y probá de nuevo.';
    end if;
    select u.email, u.encrypted_password into v_email, v_hash
    from public.user_profiles up join auth.users u on u.id = up.id
    where up.username = v_username;
    if not found then return null; end if;
    if v_hash like '$2%' and extensions.crypt(p_password, v_hash) = v_hash then
        delete from public.login_intentos where username = v_username;
        return v_email;
    end if;
    insert into public.login_intentos (username) values (v_username);
    return null;
end;
$$;

-- ---------- Permisos de las funciones ----------
-- Por defecto Postgres deja ejecutar cualquier función a PUBLIC (incluido
-- anon). Solo login_email queda abierta sin sesión.
do $$
declare f text;
begin
    foreach f in array array[
        'es_usuario_autorizado()', 'proximo_numero_remito()', 'validar_remito(jsonb, jsonb, bigint)',
        'crear_remito(jsonb, jsonb)', 'eliminar_remito(bigint)', 'anular_remito(bigint)',
        'restaurar_remito(bigint)', 'actualizar_remito(bigint, jsonb, jsonb)',
        'registrar_movimiento_stock(bigint, text, integer, text)',
        'aplicar_aumento_precios(text, double precision)', 'facturacion_mensual()',
        'ranking_productos(date, integer, text)', 'resumen_ventas(date)', 'productos_reposicion()'
    ] loop
        execute format('revoke all on function %s from public, anon', f);
        execute format('grant execute on function %s to authenticated', f);
    end loop;
end;
$$;
revoke all on function login_email(text, text) from public;
grant execute on function login_email(text, text) to anon, authenticated;

