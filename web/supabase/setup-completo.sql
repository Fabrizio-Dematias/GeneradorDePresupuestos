-- ---------- Tablas ----------

create table if not exists clientes (
    id bigint generated by default as identity primary key,
    nombre text not null,
    domicilio text,
    cuit text,
    condicion_iva text,
    condicion_venta text,
    fecha_creacion timestamptz default now()
);

create table if not exists productos (
    id bigint generated by default as identity primary key,
    codigo text unique,
    descripcion text not null,
    precio_unitario numeric(12,2) not null,
    categoria text default 'CARBONES',
    -- Datos de catálogo, opcionales: los usa la lista de precios en PDF
    -- (se agrupa por marca y muestra las columnas MEDIDAS y MOD).
    marca text,
    medidas text,
    modelo text,
    -- Control de stock: cantidad en depósito y umbral de alerta de reposición.
    stock integer not null default 0,
    stock_minimo integer not null default 0,
    fecha_actualizacion timestamptz default now()
);

create table if not exists marcas (
    nombre text primary key,
    -- Logo embebido (data URL): lo usa la lista de precios en PDF
    logo text,
    fecha_actualizacion timestamptz default now()
);

create table if not exists remitos (
    id bigint generated by default as identity primary key,
    numero text unique not null,
    fecha date not null,
    cliente_id bigint references clientes(id),
    cliente_nombre text,
    cliente_domicilio text,
    cliente_cuit text,
    -- Nuevas columnas (con default) para poder regenerar el PDF de
    -- remitos viejos desde la web. No alteran los datos existentes.
    condicion_iva text default 'Consumidor Final',
    condicion_venta text default 'Contado',
    total numeric(12,2) not null,
    estado text default 'Completado',
    ruta_pdf text,
    fecha_creacion timestamptz default now()
);

create table if not exists remito_items (
    id bigint generated by default as identity primary key,
    remito_id bigint not null references remitos(id) on delete cascade,
    codigo text,
    cantidad integer not null,
    descripcion text not null,
    precio_unitario numeric(12,2) not null,
    bonificacion numeric(5,2) default 0,
    subtotal numeric(12,2) not null
);

create table if not exists historial_precios (
    id bigint generated by default as identity primary key,
    producto_codigo text not null,
    producto_descripcion text,
    precio_anterior numeric(12,2) not null,
    precio_nuevo numeric(12,2) not null,
    porcentaje_cambio numeric(8,2),
    categoria text,
    fecha_cambio timestamptz default now()
);

-- Movimientos de stock (entradas, salidas y ajustes) para auditoría.
create table if not exists movimientos_stock (
    id bigint generated by default as identity primary key,
    producto_id bigint references productos(id) on delete set null,
    producto_codigo text,
    producto_descripcion text,
    tipo text not null,            -- 'ingreso' | 'egreso' | 'ajuste'
    cantidad integer not null,     -- magnitud del movimiento (siempre positiva)
    stock_anterior integer not null,
    stock_nuevo integer not null,
    motivo text,
    remito_id bigint references remitos(id) on delete set null,
    fecha timestamptz default now()
);

-- Login por nombre de usuario: mapea username → email de auth.users.
-- Estar en esta tabla es lo que habilita a un usuario a usar el sistema.
create table if not exists user_profiles (
    id         uuid primary key references auth.users on delete cascade,
    username   text unique not null,
    email      text not null,
    created_at timestamptz default now()
);

-- Intentos de login fallidos, para bloquear la fuerza bruta (ver login_email).
create table if not exists login_intentos (
    id       bigint generated by default as identity primary key,
    username text not null,
    fecha    timestamptz not null default now()
);

-- Cobros de remitos (control interno: no aparece en el PDF del remito).
-- Un pago puede saldar varios remitos y un remito puede pagarse en partes:
-- cada pago se reparte en imputaciones (qué parte va a cada remito).
-- Los pagos no se borran nunca: se anulan con motivo y quedan en la historia.
create table if not exists pagos (
    id               bigint generated by default as identity primary key,
    fecha            date not null default current_date,
    importe          numeric(12,2) not null check (importe > 0),
    medio            text not null default 'Efectivo',
    referencia       text,          -- n° de transferencia, de cheque, etc.
    nota             text,
    anulado          boolean not null default false,
    motivo_anulacion text,
    fecha_anulacion  timestamptz,
    anulado_por      uuid,
    creado_por       uuid default auth.uid(),
    fecha_creacion   timestamptz not null default now()
);

create table if not exists pago_imputaciones (
    id            bigint generated by default as identity primary key,
    pago_id       bigint not null references pagos(id),
    -- Si se elimina un remito cuyos pagos estaban todos anulados, la
    -- imputación queda (con el número guardado aparte) para no perder la historia
    remito_id     bigint references remitos(id) on delete set null,
    remito_numero text not null,
    importe       numeric(12,2) not null check (importe > 0)
);

-- Proveedores: un descuento único sobre su precio de lista y, opcionalmente,
-- un cargo fijo por unidad que se suma después del descuento (por ejemplo el
-- emblistado de los carbones). Costo de una unidad =
--   precio de lista × (1 − descuento/100) + cargo por unidad
create table if not exists proveedores (
    id             bigint generated by default as identity primary key,
    nombre         text not null unique check (trim(nombre) <> ''),
    contacto       text,
    telefono       text,
    email          text,
    descuento      numeric(5,2) not null default 0 check (descuento >= 0 and descuento <= 100),
    cargo_nombre   text not null default 'Emblistado',
    cargo_unitario numeric(12,2) not null default 0 check (cargo_unitario >= 0),
    notas          text,
    fecha_creacion timestamptz default now()
);

-- Código y precio de lista de cada producto en cada proveedor. Varios
-- productos propios pueden compartir el mismo código del proveedor (el mismo
-- carbón sirve para distintas herramientas), por eso el código no es único.
create table if not exists producto_proveedor (
    id                  bigint generated by default as identity primary key,
    producto_id         bigint not null references productos(id) on delete cascade,
    proveedor_id        bigint not null references proveedores(id) on delete cascade,
    codigo_proveedor    text not null check (trim(codigo_proveedor) <> ''),
    precio_lista        numeric(12,2) check (precio_lista >= 0),
    fecha_actualizacion timestamptz default now(),
    unique (proveedor_id, producto_id)
);

-- Pedidos guardados a proveedores (historial para control). Cada pedido
-- guarda una copia de cómo estaba todo al pedirlo: nombre y condiciones del
-- proveedor, y por cada línea el código DICOR, el código del proveedor, la
-- descripción y el precio de lista. Así el historial no cambia si después se
-- edita un producto o un código. Un proveedor con pedidos no se puede borrar.
create table if not exists pedidos (
    id               bigint generated by default as identity primary key,
    proveedor_id     bigint not null references proveedores(id),
    proveedor_nombre text not null,
    fecha            date not null default current_date,
    nota             text,
    descuento        numeric(5,2) not null default 0,
    cargo_nombre     text,
    cargo_unitario   numeric(12,2) not null default 0,
    total_estimado   numeric(12,2),
    creado_por       uuid default auth.uid(),
    fecha_creacion   timestamptz not null default now()
);

create table if not exists pedido_items (
    id               bigint generated by default as identity primary key,
    pedido_id        bigint not null references pedidos(id) on delete cascade,
    producto_id      bigint references productos(id) on delete set null,
    codigo_dicor     text not null,
    codigo_proveedor text not null,
    descripcion      text,
    cantidad         integer not null check (cantidad > 0),
    nota             text,
    precio_lista     numeric(12,2)
);

create index if not exists idx_productos_categoria_marca on productos (categoria, marca);
create index if not exists idx_remito_items_remito on remito_items (remito_id);
create index if not exists idx_remitos_fecha on remitos (fecha);
create index if not exists idx_historial_fecha on historial_precios (fecha_cambio desc);
create index if not exists idx_historial_codigo on historial_precios (producto_codigo);
create index if not exists idx_movimientos_producto on movimientos_stock (producto_id);
create index if not exists idx_movimientos_fecha on movimientos_stock (fecha desc);
create index if not exists idx_login_intentos on login_intentos (username, fecha);
create index if not exists idx_pago_imputaciones_remito on pago_imputaciones (remito_id);
create index if not exists idx_pago_imputaciones_pago on pago_imputaciones (pago_id);
create index if not exists idx_pagos_fecha on pagos (fecha desc);
create index if not exists idx_producto_proveedor_producto on producto_proveedor (producto_id);
