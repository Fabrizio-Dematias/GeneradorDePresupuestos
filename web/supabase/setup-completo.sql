create index if not exists idx_pedido_items_pedido on pedido_items (pedido_id);

-- ---------- Seguridad (Row Level Security) ----------
-- Solo los usuarios autenticados que además figuran en user_profiles
-- pueden leer/escribir. Una cuenta creada por fuera (signUp público) no
-- ve nada, y el público (anon) tampoco.

create or replace function es_usuario_autorizado()
returns boolean language sql security definer set search_path = '' stable as $$
    select exists (select 1 from public.user_profiles where id = auth.uid());
$$;

do $$
declare t text;
begin
    foreach t in array array['clientes','productos','marcas','remitos','remito_items',
                             'historial_precios','movimientos_stock',
                             'proveedores','producto_proveedor']
    loop
        execute format('alter table %I enable row level security', t);
        execute format('drop policy if exists "acceso total autenticado" on %I', t);
        execute format('drop policy if exists "acceso usuarios autorizados" on %I', t);
        execute format('create policy "acceso usuarios autorizados" on %I
                            for all to authenticated
                            using ((select es_usuario_autorizado()))
                            with check ((select es_usuario_autorizado()))', t);
        execute format('revoke all on table %I from anon', t);
    end loop;
end;
$$;

-- user_profiles: cada usuario solo puede leer su propio perfil. Nadie puede
-- darse de alta solo: los perfiles se cargan desde el SQL Editor.
alter table user_profiles enable row level security;
drop policy if exists "solo_propio_perfil" on user_profiles;
drop policy if exists "leer propio perfil" on user_profiles;
create policy "leer propio perfil" on user_profiles
    for select to authenticated using (auth.uid() = id);
revoke all on table user_profiles from anon;
revoke insert, update, delete, truncate, references, trigger on table user_profiles from authenticated;

-- login_intentos: solo la usa login_email (security definer).
alter table login_intentos enable row level security;
revoke all on table login_intentos from anon, authenticated;

-- Cobros y pedidos: se pueden leer, pero solo se escriben con sus funciones
-- (registrar_pagos / anular_pago, guardar_pedido / eliminar_pedido): así un
-- pago o un pedido guardado no se modifica por fuera.
do $$
declare t text;
begin
    foreach t in array array['pagos', 'pago_imputaciones', 'pedidos', 'pedido_items']
    loop
        execute format('alter table %I enable row level security', t);
        execute format('drop policy if exists "lectura usuarios autorizados" on %I', t);
        execute format('create policy "lectura usuarios autorizados" on %I
                            for select to authenticated
                            using ((select es_usuario_autorizado()))', t);
        execute format('revoke all on table %I from anon', t);
        execute format('revoke insert, update, delete, truncate, references, trigger on table %I from authenticated', t);
        execute format('grant select on table %I to authenticated', t);
    end loop;
end;
$$;

-- ---------- Funciones ----------

-- Calcula el próximo número de remito ('0001-NNN') a partir del mayor
-- sufijo existente. La web lo usa para mostrarlo; la asignación definitiva
-- la hace crear_remito bajo advisory lock.
create or replace function proximo_numero_remito()
returns text
language sql
stable
as $$
    select '0001-' || lpad(
        (coalesce(max((split_part(numero, '-', 2))::integer), 0) + 1)::text, 3, '0')
    from remitos
    where split_part(numero, '-', 2) ~ '^[0-9]+$';
$$;

-- Valida un remito antes de guardarlo y arma los ítems tal como se van a
-- guardar (lo usan crear_remito y actualizar_remito). Controla: cliente y
-- fecha presentes, al menos un ítem, cantidades enteras positivas, precios no
-- negativos, bonificación 0-100 y códigos existentes en el catálogo (un código
-- inexistente no descontaría stock y ensucia los reportes; los ítems sin
-- código siguen permitidos).
--
-- El subtotal lo calcula el servidor: el que manda el navegador no se usa.
-- Excepción al editar (p_remito_id): un ítem que ya estaba guardado en ese
-- remito y llega sin cambios (mismo código, descripción, cantidad, precio y
-- bonificación) conserva su subtotal original tal cual, sin revalidarlo. Así
-- editar un remito viejo nunca cambia los importes de lo que no se tocó,
-- aunque se haya calculado con otro redondeo.
--
-- Devuelve {items: [...], suma: <suma de los subtotales>}.
drop function if exists validar_remito(jsonb, jsonb);

create or replace function validar_remito(p_remito jsonb, p_items jsonb, p_remito_id bigint default null)
returns jsonb language plpgsql stable as $$
declare
    elem jsonb; n integer := 0;
    v_cant numeric; v_precio numeric; v_bonif numeric; v_subtotal numeric;
    v_previo_id bigint; v_usados bigint[] := '{}';
    v_items jsonb := '[]'; v_suma numeric := 0;
    v_codigos_nuevos text[] := '{}';
    v_codigos_invalidos text;
begin
    if coalesce(trim(p_remito->>'cliente_nombre'), '') = '' then
        raise exception 'Falta el nombre del cliente.';
    end if;
    if nullif(p_remito->>'fecha', '') is null then
        raise exception 'Falta la fecha del remito.';
    end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'El remito tiene que tener al menos un producto.';
    end if;
    for elem in select * from jsonb_array_elements(p_items) loop
        n := n + 1;
        if jsonb_typeof(elem->'cantidad') is distinct from 'number'
           or jsonb_typeof(elem->'precio_unitario') is distinct from 'number'
           or (elem ? 'bonificacion' and jsonb_typeof(elem->'bonificacion') not in ('number','null')) then
            raise exception 'Ítem %: cantidad, precio y bonificación tienen que ser números.', n;
        end if;
        v_cant := (elem->>'cantidad')::numeric;
        v_precio := (elem->>'precio_unitario')::numeric;
        v_bonif := coalesce((elem->>'bonificacion')::numeric, 0);

        -- ¿Es un ítem que ya estaba guardado en este remito, sin cambios?
        v_previo_id := null;
        if p_remito_id is not null then
            select ri.id, ri.subtotal into v_previo_id, v_subtotal
            from remito_items ri
            where ri.remito_id = p_remito_id
              and ri.id <> all (v_usados)
              and coalesce(ri.codigo, '') = coalesce(elem->>'codigo', '')
              and ri.descripcion = elem->>'descripcion'
              and ri.cantidad = v_cant
              and ri.precio_unitario = v_precio
              and coalesce(ri.bonificacion, 0) = v_bonif
            order by ri.id
            limit 1;
        end if;

        if v_previo_id is not null then
            v_usados := v_usados || v_previo_id;
        else
            if coalesce(trim(elem->>'descripcion'), '') = '' then
                raise exception 'Ítem %: falta la descripción.', n;
            end if;
            if v_cant <= 0 or v_cant <> trunc(v_cant) then
                raise exception 'Ítem % (%): la cantidad tiene que ser un número entero mayor a 0.', n, elem->>'descripcion';
            end if;
            if v_precio < 0 then
                raise exception 'Ítem % (%): el precio no puede ser negativo.', n, elem->>'descripcion';
            end if;
            if v_bonif < 0 or v_bonif > 100 then
                raise exception 'Ítem % (%): la bonificación tiene que estar entre 0 y 100.', n, elem->>'descripcion';
            end if;
            v_precio := round(v_precio, 2);
            v_bonif := round(v_bonif, 2);
            v_subtotal := round(v_cant * v_precio * (1 - v_bonif / 100), 2);
            if coalesce(elem->>'codigo', '') <> '' then
                v_codigos_nuevos := v_codigos_nuevos || (elem->>'codigo');
            end if;
        end if;

        v_items := v_items || jsonb_build_array(jsonb_build_object(
            'codigo', elem->>'codigo',
            'cantidad', v_cant::integer,
            'descripcion', elem->>'descripcion',
            'precio_unitario', v_precio,
            'bonificacion', v_bonif,
            'subtotal', v_subtotal));
        v_suma := v_suma + v_subtotal;
    end loop;

    select string_agg(distinct c, ', ') into v_codigos_invalidos
    from unnest(v_codigos_nuevos) as c
    where not exists (select 1 from productos p where p.codigo = c);
    if v_codigos_invalidos is not null then
        raise exception 'Estos códigos no existen en el catálogo: %. Corregilos o dejá el código vacío.', v_codigos_invalidos;
    end if;

    return jsonb_build_object('items', v_items, 'suma', v_suma);
end;
$$;

-- Crea el remito y sus items en una sola transacción (todo o nada) y
-- descuenta el stock de cada ítem cuyo código exista en el catálogo,
-- dejando registrado el movimiento. El número, los subtotales y el total se
-- calculan en el servidor (el número serializado con advisory lock) y se
-- devuelven en el jsonb {id, numero, total, items}.
drop function if exists crear_remito(jsonb, jsonb);

create or replace function crear_remito(p_remito jsonb, p_items jsonb)
returns jsonb
language plpgsql
as $$
declare
    v_id bigint;
    v_numero text;
    v_validado jsonb;
    v_items jsonb;
    v_total numeric;
    i jsonb;
    v_cant integer;
    v_prod_id bigint;
    v_prod_codigo text;
    v_prod_desc text;
    v_anterior integer;
    v_nuevo integer;
begin
    v_validado := validar_remito(p_remito, p_items);
    v_items := v_validado->'items';
    v_total := (v_validado->>'suma')::numeric;

    -- Serializa la asignación del número entre transacciones concurrentes
    perform pg_advisory_xact_lock(hashtext('remitos_numero'));
    v_numero := proximo_numero_remito();

    insert into remitos (numero, fecha, cliente_id, cliente_nombre, cliente_domicilio, cliente_cuit,
                         condicion_iva, condicion_venta, total, ruta_pdf)
    values (
        v_numero,
        (p_remito->>'fecha')::date,
        nullif(p_remito->>'cliente_id', '')::bigint,
        p_remito->>'cliente_nombre',
        p_remito->>'cliente_domicilio',
        p_remito->>'cliente_cuit',
        coalesce(p_remito->>'condicion_iva', 'Consumidor Final'),
        coalesce(p_remito->>'condicion_venta', 'Contado'),
        v_total,
        'remito_' || regexp_replace(coalesce(p_remito->>'cliente_nombre', ''), '[^a-zA-Z0-9]', '_', 'g')
            || '_' || v_numero || '.pdf'
    )
    returning id into v_id;

    insert into remito_items (remito_id, codigo, cantidad, descripcion, precio_unitario, bonificacion, subtotal)
    select
        v_id,
        elem->>'codigo',
        (elem->>'cantidad')::integer,
        elem->>'descripcion',
        (elem->>'precio_unitario')::numeric,
        (elem->>'bonificacion')::numeric,
        (elem->>'subtotal')::numeric
    from jsonb_array_elements(v_items) as elem;

    -- Descuento de stock por cada ítem con código existente.
    -- El UPDATE es relativo (stock = stock - v_cant) y atómico: evita el
    -- "lost update" si se generan dos remitos del mismo producto a la vez.
    -- Se permite stock negativo a propósito: refleja una venta real aunque
    -- el stock cargado no alcance (queda en rojo como aviso de reposición).
    for i in select * from jsonb_array_elements(v_items)
    loop
        v_cant := coalesce((i->>'cantidad')::integer, 0);
        if v_cant > 0 and coalesce(i->>'codigo', '') <> '' then
            update productos
            set stock = stock - v_cant
            where codigo = (i->>'codigo')
            returning id, codigo, descripcion, stock + v_cant, stock
            into v_prod_id, v_prod_codigo, v_prod_desc, v_anterior, v_nuevo;
            if found then
                insert into movimientos_stock (producto_id, producto_codigo, producto_descripcion,
                                               tipo, cantidad, stock_anterior, stock_nuevo, motivo, remito_id)
                values (v_prod_id, v_prod_codigo, v_prod_desc,
                        'egreso', v_cant, v_anterior, v_nuevo,
                        'Venta · remito ' || v_numero, v_id);
            end if;
        end if;
    end loop;

    return jsonb_build_object('id', v_id, 'numero', v_numero, 'total', v_total, 'items', v_items);
end;
$$;

-- Elimina un remito reponiendo el stock descontado al crearlo y dejando
-- registrado el movimiento de reposición. Los items se borran en cascada.
-- Si el remito ya estaba anulado, el stock ya fue repuesto al anularlo:
-- borrar no debe volver a sumarlo.
create or replace function eliminar_remito(p_remito_id bigint)
returns void
language plpgsql
as $$
declare
    v_numero text;
    v_estado text;
    it record;
    v_prod_id bigint;
    v_codigo text;
    v_desc text;
    v_anterior integer;
    v_nuevo integer;
begin
    select numero, coalesce(estado, 'Completado')
    into v_numero, v_estado
    from remitos where id = p_remito_id for update;
    if not found then
        raise exception 'Remito % no encontrado', p_remito_id;
    end if;

    if v_estado <> 'Anulado' then
        for it in
            select codigo, sum(cantidad) as cantidad
            from remito_items
            where remito_id = p_remito_id and coalesce(codigo, '') <> '' and cantidad > 0
            group by codigo
        loop
            update productos
            set stock = stock + it.cantidad
            where codigo = it.codigo
            returning id, codigo, descripcion, stock - it.cantidad, stock
            into v_prod_id, v_codigo, v_desc, v_anterior, v_nuevo;
            if found then
                insert into movimientos_stock (producto_id, producto_codigo, producto_descripcion,
                                               tipo, cantidad, stock_anterior, stock_nuevo, motivo)
                values (v_prod_id, v_codigo, v_desc,
                        'ingreso', it.cantidad, v_anterior, v_nuevo,
                        'Reposición · remito ' || v_numero || ' eliminado');
            end if;
        end loop;
    end if;

    delete from remitos where id = p_remito_id;
end;
$$;

-- Anula un remito: repone el stock (con auditoría) y marca estado='Anulado'.
-- El remito queda visible en el listado pero excluido de las métricas.
create or replace function anular_remito(p_remito_id bigint)
returns void
language plpgsql
as $$
declare
    v_numero text;
    v_estado text;
    it record;
    v_prod_id bigint;
