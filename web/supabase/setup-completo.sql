-- Edita un remito: repone el stock de los items originales, reemplaza los
-- items y datos (el número no cambia) y descuenta el stock nuevo.
-- El total nuevo es el total guardado + lo que suman los ítems nuevos − lo que
-- sumaban los anteriores: si los ítems no cambian, el total queda idéntico
-- (también en los remitos viejos cuyo total no coincide con la suma de sus
-- ítems), y si cambian, se mueve exactamente por la diferencia.
create or replace function actualizar_remito(p_remito_id bigint, p_remito jsonb, p_items jsonb)
returns jsonb
language plpgsql
as $$
declare
    v_numero text;
    v_estado text;
    v_total_anterior numeric;
    v_suma_anterior numeric;
    v_validado jsonb;
    v_items jsonb;
    v_total numeric;
    it record;
    i jsonb;
    v_cant integer;
    v_prod_id bigint;
    v_codigo text;
    v_desc text;
    v_anterior integer;
    v_nuevo integer;
begin
    select numero, coalesce(estado, 'Completado'), total
    into v_numero, v_estado, v_total_anterior
    from remitos where id = p_remito_id for update;
    if not found then
        raise exception 'Remito % no encontrado', p_remito_id;
    end if;
    if v_estado = 'Anulado' then
        raise exception 'El remito % está anulado y no se puede editar', v_numero;
    end if;

    -- Misma validación que en crear_remito, antes de tocar nada. Los ítems
    -- que no cambiaron conservan su subtotal original.
    v_validado := validar_remito(p_remito, p_items, p_remito_id);
    v_items := v_validado->'items';
    select coalesce(sum(subtotal), 0) into v_suma_anterior
    from remito_items where remito_id = p_remito_id;
    v_total := v_total_anterior + (v_validado->>'suma')::numeric - v_suma_anterior;
    if v_total < 0 then
        raise exception 'El total del remito % quedaría negativo (%). Revisá los ítems.', v_numero, v_total;
    end if;

    for it in
        select codigo, sum(cantidad) as cantidad
        from remito_items
        where remito_id = p_remito_id and coalesce(codigo, '') <> '' and cantidad > 0
        group by codigo
    loop
        update productos
        set stock = stock + it.cantidad
        where codigo = it.codigo
        returning id, codigo, descripcion, stock - it.cantidad, stock
        into v_prod_id, v_codigo, v_desc, v_anterior, v_nuevo;
        if found then
            insert into movimientos_stock (producto_id, producto_codigo, producto_descripcion,
                                           tipo, cantidad, stock_anterior, stock_nuevo, motivo, remito_id)
            values (v_prod_id, v_codigo, v_desc,
                    'ingreso', it.cantidad, v_anterior, v_nuevo,
                    'Edición · remito ' || v_numero || ' (reversión)', p_remito_id);
        end if;
    end loop;

    delete from remito_items where remito_id = p_remito_id;

    update remitos
    set fecha             = (p_remito->>'fecha')::date,
        cliente_id        = nullif(p_remito->>'cliente_id', '')::bigint,
        cliente_nombre    = p_remito->>'cliente_nombre',
        cliente_domicilio = p_remito->>'cliente_domicilio',
        cliente_cuit      = p_remito->>'cliente_cuit',
        condicion_iva     = coalesce(p_remito->>'condicion_iva', 'Consumidor Final'),
        condicion_venta   = coalesce(p_remito->>'condicion_venta', 'Contado'),
        total             = v_total,
        ruta_pdf          = 'remito_' || regexp_replace(coalesce(p_remito->>'cliente_nombre', ''), '[^a-zA-Z0-9]', '_', 'g')
                                || '_' || v_numero || '.pdf'
    where id = p_remito_id;

    insert into remito_items (remito_id, codigo, cantidad, descripcion, precio_unitario, bonificacion, subtotal)
    select
        p_remito_id,
        elem->>'codigo',
        (elem->>'cantidad')::integer,
        elem->>'descripcion',
        (elem->>'precio_unitario')::numeric,
        (elem->>'bonificacion')::numeric,
        (elem->>'subtotal')::numeric
    from jsonb_array_elements(v_items) as elem;

    for i in select * from jsonb_array_elements(v_items)
    loop
        v_cant := coalesce((i->>'cantidad')::integer, 0);
        if v_cant > 0 and coalesce(i->>'codigo', '') <> '' then
            update productos
            set stock = stock - v_cant
            where codigo = (i->>'codigo')
            returning id, codigo, descripcion, stock + v_cant, stock
            into v_prod_id, v_codigo, v_desc, v_anterior, v_nuevo;
            if found then
                insert into movimientos_stock (producto_id, producto_codigo, producto_descripcion,
                                               tipo, cantidad, stock_anterior, stock_nuevo, motivo, remito_id)
                values (v_prod_id, v_codigo, v_desc,
                        'egreso', v_cant, v_anterior, v_nuevo,
                        'Venta · remito ' || v_numero || ' (editado)', p_remito_id);
            end if;
        end if;
    end loop;

    return jsonb_build_object('id', p_remito_id, 'numero', v_numero, 'total', v_total, 'items', v_items);
end;
$$;

-- Registra un movimiento de stock manual (ingreso/egreso/ajuste),
-- actualizando el producto y dejando el registro de auditoría.
create or replace function registrar_movimiento_stock(
    p_producto_id bigint,
    p_tipo text,
    p_cantidad integer,
    p_motivo text
)
returns integer
language plpgsql
as $$
declare
    v_codigo text;
    v_desc text;
    v_anterior integer;
    v_nuevo integer;
    v_magnitud integer;
begin
    if p_tipo in ('ingreso', 'egreso') and p_cantidad < 0 then
        raise exception 'La cantidad no puede ser negativa';
    end if;

    if p_tipo = 'ingreso' then
        -- UPDATE relativo y atómico: evita "lost update" entre movimientos concurrentes
        v_magnitud := abs(p_cantidad);
        update productos set stock = stock + v_magnitud, fecha_actualizacion = now()
        where id = p_producto_id
        returning codigo, descripcion, stock - v_magnitud, stock
        into v_codigo, v_desc, v_anterior, v_nuevo;
    elsif p_tipo = 'egreso' then
        v_magnitud := abs(p_cantidad);
        update productos set stock = stock - v_magnitud, fecha_actualizacion = now()
        where id = p_producto_id
        returning codigo, descripcion, stock + v_magnitud, stock
        into v_codigo, v_desc, v_anterior, v_nuevo;
    elsif p_tipo = 'ajuste' then
        -- Ajuste fija un valor absoluto: se toma lock de la fila (for update)
        -- para leer el stock previo de forma consistente antes de sobreescribir.
        select stock, codigo, descripcion into v_anterior, v_codigo, v_desc
        from productos where id = p_producto_id for update;
        if not found then
            raise exception 'Producto % no encontrado', p_producto_id;
        end if;
        v_nuevo := p_cantidad;
        v_magnitud := abs(p_cantidad - coalesce(v_anterior, 0));
        update productos set stock = v_nuevo, fecha_actualizacion = now()
        where id = p_producto_id;
    else
        raise exception 'Tipo de movimiento inválido: %', p_tipo;
    end if;

    if not found then
        raise exception 'Producto % no encontrado', p_producto_id;
    end if;

    insert into movimientos_stock (producto_id, producto_codigo, producto_descripcion,
                                   tipo, cantidad, stock_anterior, stock_nuevo, motivo)
    values (p_producto_id, v_codigo, v_desc,
            p_tipo, v_magnitud, coalesce(v_anterior, 0), v_nuevo, coalesce(p_motivo, ''));

    return v_nuevo;
end;
$$;

-- Aplica un aumento (o baja, con porcentaje negativo) a una categoría
-- o a todos los productos, registrando cada cambio en historial_precios.
create or replace function aplicar_aumento_precios(p_categoria text, p_porcentaje double precision)
returns integer
language plpgsql
as $$
declare
    v_count integer;
begin
    insert into historial_precios (producto_codigo, producto_descripcion, precio_anterior,
                                   precio_nuevo, porcentaje_cambio, categoria)
    select codigo, descripcion, precio_unitario,
           precio_unitario * (1 + p_porcentaje / 100.0), p_porcentaje, categoria
    from productos
    where p_categoria is null or p_categoria in ('TODAS', 'TODOS') or categoria = p_categoria;

    update productos
    set precio_unitario = precio_unitario * (1 + p_porcentaje / 100.0),
        fecha_actualizacion = now()
    where p_categoria is null or p_categoria in ('TODAS', 'TODOS') or categoria = p_categoria;

    get diagnostics v_count = row_count;
    return v_count;
end;
$$;

-- ---------- Cobros (control interno) ----------

-- Protege los remitos que tienen pagos vigentes: no se pueden eliminar ni
-- anular, y al editarlos el total no puede quedar por debajo de lo cobrado.
-- Es un trigger para que valga por cualquier camino (funciones o API).
create or replace function proteger_remito_con_pagos()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
    v_cobrado numeric;
begin
    select coalesce(sum(pi.importe), 0) into v_cobrado
    from public.pago_imputaciones pi
    join public.pagos p on p.id = pi.pago_id
    where pi.remito_id = old.id and not p.anulado;

    if v_cobrado > 0 then
        if tg_op = 'DELETE' then
            raise exception 'El remito % tiene pagos registrados por $%. Anulá esos pagos antes de eliminarlo.',
                old.numero, v_cobrado;
        end if;
        if coalesce(new.estado, '') = 'Anulado' and coalesce(old.estado, '') <> 'Anulado' then
            raise exception 'El remito % tiene pagos registrados por $%. Anulá esos pagos antes de anular el remito.',
                old.numero, v_cobrado;
        end if;
        if new.total < v_cobrado then
            raise exception 'El remito % ya tiene cobrados $% y el total nuevo ($%) quedaría por debajo. Anulá o corregí los pagos primero.',
                old.numero, v_cobrado, new.total;
        end if;
    end if;

    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;

create or replace trigger remitos_proteger_pagos
    before update or delete on remitos
    for each row execute function proteger_remito_con_pagos();

-- Remitos con su situación de cobro: cobrado, saldo y estado
-- ('pendiente', 'parcial', 'cobrado' o 'anulado'). Es una vista: no copia ni
-- modifica nada de los remitos, se calcula cada vez a partir de los pagos.
create or replace view remitos_con_cobro with (security_invoker = true) as
select r.id, r.numero, r.fecha, r.cliente_id, r.cliente_nombre, r.cliente_domicilio, r.cliente_cuit,
       r.condicion_iva, r.condicion_venta, r.total, r.estado, r.ruta_pdf, r.fecha_creacion,
       coalesce(c.cobrado, 0)::numeric(12,2) as cobrado,
       (case when coalesce(r.estado, '') = 'Anulado' then 0
             else greatest(r.total - coalesce(c.cobrado, 0), 0) end)::numeric(12,2) as saldo,
       case when coalesce(r.estado, '') = 'Anulado' then 'anulado'
            when coalesce(c.cobrado, 0) >= r.total then 'cobrado'
            when coalesce(c.cobrado, 0) > 0 then 'parcial'
            else 'pendiente' end as estado_cobro,
       c.ultimo_pago
from public.remitos r
left join (
    select pi.remito_id, sum(pi.importe) as cobrado, max(p.fecha) as ultimo_pago
    from public.pago_imputaciones pi
    join public.pagos p on p.id = pi.pago_id
    where not p.anulado
    group by pi.remito_id
) c on c.remito_id = r.id;

revoke all on table remitos_con_cobro from anon;
revoke insert, update, delete, truncate, references, trigger on table remitos_con_cobro from authenticated;
grant select on table remitos_con_cobro to authenticated;

-- Registra uno o varios pagos en una sola transacción (todo o nada).
-- p_pagos: [{fecha, medio, referencia, nota, imputaciones: [{remito_id, importe}]}]
-- El importe de cada pago es la suma de sus imputaciones. Cada imputación no
-- puede superar el saldo pendiente del remito, y un remito anulado no se cobra.
create or replace function registrar_pagos(p_pagos jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
    v_pago jsonb; v_imp jsonb;
    n integer := 0;
    v_fecha date; v_medio text; v_referencia text; v_nota text;
    v_importe numeric; v_total numeric; v_cobrado numeric; v_saldo numeric;
    v_rid bigint; v_ids bigint[] := '{}';
    v_numero text; v_estado text; v_total_remito numeric;
    v_pago_id bigint;
    v_resultado jsonb := '[]';
begin
    if not public.es_usuario_autorizado() then
        raise exception 'No autorizado.';
    end if;
    if p_pagos is null or jsonb_typeof(p_pagos) <> 'array' or jsonb_array_length(p_pagos) = 0 then
        raise exception 'No hay pagos para registrar.';
    end if;

    -- 1. Validación de forma, antes de tocar nada
    for v_pago in select * from jsonb_array_elements(p_pagos) loop
        n := n + 1;
        if jsonb_typeof(v_pago) is distinct from 'object'
           or jsonb_typeof(v_pago->'imputaciones') is distinct from 'array'
           or jsonb_array_length(v_pago->'imputaciones') = 0 then
            raise exception 'Pago %: tiene que indicar al menos un remito.', n;
        end if;
        v_fecha := coalesce(nullif(v_pago->>'fecha', '')::date, current_date);
        if v_fecha > current_date then
            raise exception 'Pago %: la fecha no puede ser posterior a hoy.', n;
        end if;
        if coalesce(nullif(trim(v_pago->>'medio'), ''), 'Efectivo')
           not in ('Efectivo', 'Transferencia', 'Cheque', 'Mercado Pago', 'Tarjeta', 'Otro') then
            raise exception 'Pago %: medio de pago inválido (%).', n, v_pago->>'medio';
        end if;
        if length(coalesce(v_pago->>'referencia', '')) > 200 or length(coalesce(v_pago->>'nota', '')) > 500 then
            raise exception 'Pago %: la referencia o la nota son demasiado largas.', n;
        end if;
        for v_imp in select * from jsonb_array_elements(v_pago->'imputaciones') loop
            if jsonb_typeof(v_imp->'remito_id') is distinct from 'number'
               or jsonb_typeof(v_imp->'importe') is distinct from 'number' then
                raise exception 'Pago %: cada remito tiene que indicar remito_id e importe numéricos.', n;
            end if;
            v_rid := (v_imp->>'remito_id')::bigint;
            if v_rid = any (v_ids) then
                raise exception 'El mismo remito aparece dos veces en el cobro.';
            end if;
            v_ids := v_ids || v_rid;
            if round((v_imp->>'importe')::numeric, 2) <= 0 then
                raise exception 'Pago %: los importes tienen que ser mayores a 0.', n;
            end if;
        end loop;
    end loop;

    -- 2. Bloquea los remitos involucrados (en orden, para que dos cobros
    --    simultáneos del mismo remito no se pisen el saldo)
    perform 1 from public.remitos where id = any (v_ids) order by id for update;

    -- 3. Controla saldos y registra
    n := 0;
    for v_pago in select * from jsonb_array_elements(p_pagos) loop
        n := n + 1;
        v_fecha := coalesce(nullif(v_pago->>'fecha', '')::date, current_date);
        v_medio := coalesce(nullif(trim(v_pago->>'medio'), ''), 'Efectivo');
        v_referencia := nullif(trim(coalesce(v_pago->>'referencia', '')), '');
        v_nota := nullif(trim(coalesce(v_pago->>'nota', '')), '');
        v_total := 0;

        for v_imp in select * from jsonb_array_elements(v_pago->'imputaciones') loop
            v_rid := (v_imp->>'remito_id')::bigint;
            v_importe := round((v_imp->>'importe')::numeric, 2);
            select numero, coalesce(estado, 'Completado'), total
            into v_numero, v_estado, v_total_remito
            from public.remitos where id = v_rid;
            if not found then
                raise exception 'El remito % no existe.', v_rid;
            end if;
            if v_estado = 'Anulado' then
                raise exception 'El remito % está anulado: no se le pueden registrar pagos.', v_numero;
            end if;
            select coalesce(sum(pi.importe), 0) into v_cobrado
            from public.pago_imputaciones pi
            join public.pagos p on p.id = pi.pago_id
            where pi.remito_id = v_rid and not p.anulado;
            v_saldo := v_total_remito - v_cobrado;
            if v_importe > v_saldo then
                raise exception 'Remito %: el pago ($%) supera el saldo pendiente ($%).', v_numero, v_importe, greatest(v_saldo, 0);
            end if;
            v_total := v_total + v_importe;
        end loop;

        insert into public.pagos (fecha, importe, medio, referencia, nota)
        values (v_fecha, v_total, v_medio, v_referencia, v_nota)
        returning id into v_pago_id;

        insert into public.pago_imputaciones (pago_id, remito_id, remito_numero, importe)
        select v_pago_id, r.id, r.numero, round((i->>'importe')::numeric, 2)
        from jsonb_array_elements(v_pago->'imputaciones') as i
        join public.remitos r on r.id = (i->>'remito_id')::bigint;

        v_resultado := v_resultado || jsonb_build_array(jsonb_build_object('id', v_pago_id, 'importe', v_total));
    end loop;

    return v_resultado;
end;
$$;

-- Anula un pago completo (con todas sus imputaciones). No se borra: queda
-- marcado como anulado, con el motivo, la fecha y quién lo anuló.
create or replace function anular_pago(p_pago_id bigint, p_motivo text)
returns void language plpgsql security definer set search_path = '' as $$
begin
    if not public.es_usuario_autorizado() then
        raise exception 'No autorizado.';
    end if;
    if coalesce(trim(p_motivo), '') = '' then
        raise exception 'Indicá el motivo de la anulación.';
    end if;
    if length(p_motivo) > 500 then
        raise exception 'El motivo es demasiado largo.';
    end if;
    update public.pagos
    set anulado = true, motivo_anulacion = trim(p_motivo),
        fecha_anulacion = now(), anulado_por = auth.uid()
    where id = p_pago_id and not anulado;
    if not found then
        raise exception 'El pago no existe o ya estaba anulado.';
    end if;
end;
$$;

-- Lo que falta cobrar, agrupado por cliente (por el cliente guardado, o por
-- el nombre si el remito no tiene cliente asociado). Los que más deben primero.
create or replace function deudas_por_cliente()
returns table (cliente_id bigint, cliente_nombre text, remitos bigint, saldo numeric, desde date)
language sql stable set search_path = '' as $$
    select max(r.cliente_id), max(r.cliente_nombre), count(*), sum(r.saldo), min(r.fecha)
    from public.remitos_con_cobro r
    where r.estado_cobro in ('pendiente', 'parcial')
    group by coalesce(r.cliente_id::text, lower(trim(coalesce(r.cliente_nombre, ''))))
    order by sum(r.saldo) desc;
$$;

-- ---------- Pedidos a proveedores ----------

-- Guarda un pedido con sus líneas en una sola transacción. Del navegador
-- solo se toman producto, cantidad y nota: los códigos, la descripción, los
-- precios y las condiciones del proveedor se copian de la base en ese momento.
-- p_items: [{producto_id, cantidad, nota}]
create or replace function guardar_pedido(p_proveedor_id bigint, p_items jsonb,
                                          p_nota text default null, p_fecha date default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
    v_proveedor record;
    v_fecha date := coalesce(p_fecha, current_date);
    v_elem jsonb; n integer := 0;
    v_cantidad numeric; v_producto_id bigint; v_ids bigint[] := '{}';
    v_precio numeric; v_lista numeric := 0; v_unidades numeric := 0; v_total numeric;
    v_id bigint;
begin
    if not public.es_usuario_autorizado() then
        raise exception 'No autorizado.';
    end if;
    select id, nombre, descuento, cargo_nombre, cargo_unitario into v_proveedor
    from public.proveedores where id = p_proveedor_id;
    if not found then
        raise exception 'El proveedor no existe.';
    end if;
    if v_fecha > current_date then
        raise exception 'La fecha del pedido no puede ser posterior a hoy.';
    end if;
    if length(coalesce(p_nota, '')) > 500 then
        raise exception 'La nota del pedido es demasiado larga.';
    end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'El pedido no tiene productos.';
    end if;

    for v_elem in select * from jsonb_array_elements(p_items) loop
        n := n + 1;
        if jsonb_typeof(v_elem->'producto_id') is distinct from 'number'
           or jsonb_typeof(v_elem->'cantidad') is distinct from 'number' then
            raise exception 'Línea %: producto y cantidad tienen que ser números.', n;
        end if;
        v_cantidad := (v_elem->>'cantidad')::numeric;
        if v_cantidad <= 0 or v_cantidad <> trunc(v_cantidad) or v_cantidad > 1000000 then
            raise exception 'Línea %: la cantidad tiene que ser un número entero mayor a 0.', n;
        end if;
        if length(coalesce(v_elem->>'nota', '')) > 100 then
            raise exception 'Línea %: la nota es demasiado larga.', n;
        end if;
        v_producto_id := (v_elem->>'producto_id')::bigint;
        if v_producto_id = any (v_ids) then
            raise exception 'Un producto aparece dos veces en el pedido.';
        end if;
        v_ids := v_ids || v_producto_id;
        select pp.precio_lista into v_precio
        from public.producto_proveedor pp
        where pp.producto_id = v_producto_id and pp.proveedor_id = p_proveedor_id;
        if not found then
            raise exception 'Línea %: el producto no tiene código de %.', n, v_proveedor.nombre;
        end if;
        v_unidades := v_unidades + v_cantidad;
        v_lista := v_lista + v_cantidad * coalesce(v_precio, 0);
    end loop;

    -- Mismo armado que la factura del proveedor: lista − descuento + cargo × unidades
    v_total := round(v_lista * (1 - v_proveedor.descuento / 100) + v_unidades * v_proveedor.cargo_unitario, 2);

    insert into public.pedidos (proveedor_id, proveedor_nombre, fecha, nota, descuento,
                                cargo_nombre, cargo_unitario, total_estimado)
    values (v_proveedor.id, v_proveedor.nombre, v_fecha, nullif(trim(coalesce(p_nota, '')), ''),
            v_proveedor.descuento, v_proveedor.cargo_nombre, v_proveedor.cargo_unitario, v_total)
    returning id into v_id;

    insert into public.pedido_items (pedido_id, producto_id, codigo_dicor, codigo_proveedor,
                                     descripcion, cantidad, nota, precio_lista)
    select v_id, p.id, p.codigo, pp.codigo_proveedor, p.descripcion,
           (e->>'cantidad')::integer, nullif(trim(coalesce(e->>'nota', '')), ''), pp.precio_lista
    from jsonb_array_elements(p_items) as e
    join public.productos p on p.id = (e->>'producto_id')::bigint
    join public.producto_proveedor pp on pp.producto_id = p.id and pp.proveedor_id = p_proveedor_id;

    return jsonb_build_object('id', v_id, 'total_estimado', v_total, 'unidades', v_unidades);
end;
$$;

-- Elimina un pedido guardado (por ejemplo, si se guardó por error) con sus líneas.
create or replace function eliminar_pedido(p_pedido_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
    if not public.es_usuario_autorizado() then
        raise exception 'No autorizado.';
    end if;
    delete from public.pedidos where id = p_pedido_id;
    if not found then
        raise exception 'El pedido no existe.';
    end if;
end;
$$;

-- ---------- Agregaciones en el servidor ----------
-- Usadas por Dashboard, Facturación mensual y Más vendidos.
-- Todas excluyen los remitos anulados.

create or replace function facturacion_mensual()
returns table (anio integer, mes integer, cantidad bigint, total numeric)
language sql
stable
as $$
    select extract(year from fecha)::integer,
           extract(month from fecha)::integer,
           count(*),
           coalesce(sum(total), 0)
    from remitos
    where coalesce(estado, '') <> 'Anulado'
    group by 1, 2
    order by 1, 2;
$$;

create or replace function ranking_productos(p_desde date, p_limite integer, p_orden text default 'cantidad')
returns table (codigo text, descripcion text, categoria text, cantidad bigint, facturado numeric)
language sql
stable
as $$
    select coalesce(ri.codigo, '—'),
           ri.descripcion,
           coalesce(p.categoria, 'SIN CATEGORÍA'),
           sum(ri.cantidad)::bigint,
           coalesce(sum(ri.subtotal), 0)
    from remito_items ri
    join remitos r on r.id = ri.remito_id
    left join productos p on p.codigo = ri.codigo
    where coalesce(r.estado, '') <> 'Anulado'
      and (p_desde is null or r.fecha >= p_desde)
    group by 1, 2, 3
    order by case when p_orden = 'facturado' then coalesce(sum(ri.subtotal), 0)
                  else sum(ri.cantidad)::numeric end desc
    limit p_limite;
$$;

create or replace function resumen_ventas(p_desde date)
returns table (unidades bigint, productos_distintos bigint, facturado numeric)
language sql
stable
as $$
    select coalesce(sum(ri.cantidad), 0)::bigint,
           count(distinct coalesce(ri.codigo, '') || '|' || ri.descripcion),
           coalesce(sum(ri.subtotal), 0)
    from remito_items ri
    join remitos r on r.id = ri.remito_id
    where coalesce(r.estado, '') <> 'Anulado'
      and (p_desde is null or r.fecha >= p_desde);
$$;

create or replace function productos_reposicion()
returns table (codigo text, descripcion text, stock integer, stock_minimo integer)
language sql
stable
as $$
    select codigo, descripcion, stock, stock_minimo
    from productos
    where stock <= 0 or (stock_minimo > 0 and stock <= stock_minimo)
    order by stock;
$$;


-- ---------- Login por nombre de usuario ----------
-- La tabla user_profiles NO es legible con la anon key: el lookup del login
-- pasa por esta función security definer, que verifica la contraseña antes
-- de devolver el email (si no, revelaría el email de cualquier usuario).
-- Con 5 intentos fallidos en 15 minutos el usuario queda bloqueado ese rato.
create extension if not exists pgcrypto with schema extensions;
drop function if exists login_email(text);

create or replace function login_email(p_username text, p_password text)
returns text language plpgsql security definer set search_path = '' as $$
declare
    v_username text := lower(trim(coalesce(p_username, '')));
    v_email text; v_hash text;
begin
    if v_username = '' or length(v_username) > 100
       or coalesce(p_password, '') = '' or length(p_password) > 200 then
        return null;
    end if;
    delete from public.login_intentos where fecha < now() - interval '1 day';
    if (select count(*) from public.login_intentos
        where username = v_username and fecha > now() - interval '15 minutes') >= 5 then
        raise exception 'Demasiados intentos fallidos. Esperá 15 minutos y probá de nuevo.';
    end if;
    select u.email, u.encrypted_password into v_email, v_hash
    from public.user_profiles up join auth.users u on u.id = up.id
    where up.username = v_username;
    if not found then return null; end if;
    if v_hash like '$2%' and extensions.crypt(p_password, v_hash) = v_hash then
        delete from public.login_intentos where username = v_username;
        return v_email;
    end if;
    insert into public.login_intentos (username) values (v_username);
    return null;
end;
$$;

-- ---------- Permisos de las funciones ----------
-- Por defecto Postgres deja ejecutar cualquier función a PUBLIC (incluido
-- anon). Solo login_email queda abierta sin sesión.
do $$
declare f text;
begin
    foreach f in array array[
        'es_usuario_autorizado()', 'proximo_numero_remito()', 'validar_remito(jsonb, jsonb, bigint)',
        'crear_remito(jsonb, jsonb)', 'eliminar_remito(bigint)', 'anular_remito(bigint)',
        'restaurar_remito(bigint)', 'actualizar_remito(bigint, jsonb, jsonb)',
        'registrar_movimiento_stock(bigint, text, integer, text)',
        'aplicar_aumento_precios(text, double precision)', 'facturacion_mensual()',
        'ranking_productos(date, integer, text)', 'resumen_ventas(date)', 'productos_reposicion()',
        'proteger_remito_con_pagos()', 'registrar_pagos(jsonb)', 'anular_pago(bigint, text)',
        'deudas_por_cliente()', 'guardar_pedido(bigint, jsonb, text, date)', 'eliminar_pedido(bigint)'
    ] loop
        execute format('revoke all on function %s from public, anon', f);
        execute format('grant execute on function %s to authenticated', f);
    end loop;
end;
$$;
revoke all on function login_email(text, text) from public;
grant execute on function login_email(text, text) to anon, authenticated;

