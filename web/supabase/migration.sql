-- Mismo formato de tablas que la app de escritorio (dicor.db),
-- incluida la tabla historial_precios que en el escritorio
-- nunca se creaba (causa del bug del historial).
--
-- Ejecutar UNA VEZ en: Supabase Dashboard → SQL Editor → New query
-- Después ejecutar seed.sql para cargar los datos.
